def _num(src):
    st = {'ch': 0, 'f': 0, 's': 0}
    def rep(m):
        t = m.group(0)
        if t.startswith('<section'):
            st['ch'] = int(m.group(1)); st['f'] = 0; st['s'] = 0; return t
        if t == '@@FIG@@':
            st['f'] += 1; return f"{st['ch']}.{st['f']}"
        st['s'] += 1
        sn = f"{st['ch']}.{st['s']}"; sid = f"s{st['ch']}-{st['s']}"
        title = m.group(2)
        TOC[st['ch'] - 1][3].append((sn, title, sid))
        return f'<div class="sec" id="{sid}"><h2><span class="sn">{sn}</span>{title}</h2>'
    return re.sub(r'<section class="chapter" id="ch(\d+)"|@@FIG@@|<div class="sec" id="@@SID@@"><h2><span class="sn">@@SN@@</span>(.*?)</h2>', rep, src)
