FIG = [0]
CH = [0]
OUT = []
TOC = []

def esc(s): return s  # content is trusted, written here

def where(*parts):
    chips = ''.join(f'<span class="wp">{p}</span>' for p in parts)
    return f'<div class="where"><span class="wl">อยู่ที่</span>{chips}</div>'

def fig(name, cap, cls=''):
    FIG[0] += 1
    return (f'<figure class="{cls}"><img src="img/{name}.jpg" alt="{cap}" loading="lazy">'
            f'<figcaption><b>รูป @@FIG@@</b> {cap}</figcaption></figure>')

def phones(names_caps):
    out = '<div class="phones">'
    for n, c in names_caps:
        FIG[0] += 1
        out += f'<figure class="phone"><img src="img/{n}.jpg" alt="{c}" loading="lazy"><figcaption><b>รูป @@FIG@@</b> {c}</figcaption></figure>'
    return out + '</div>'

def steps(*items, start=1):
    lis = ''.join(f'<li><span class="n">{i+start}</span><div>{t}</div></li>' for i, t in enumerate(items))
    return f'<ol class="steps">{lis}</ol>'

def bullets(*items):
    return '<ul>' + ''.join(f'<li>{t}</li>' for t in items) + '</ul>'

def tip(t): return f'<div class="box tip"><b>เคล็ดลับ</b>{t}</div>'
def warn(t): return f'<div class="box warn"><b>ระวัง</b>{t}</div>'
def note(t): return f'<div class="box note"><b>รู้ไว้</b>{t}</div>'
def p(t): return f'<p>{t}</p>'
def btn(t): return f'<span class="btn">{t}</span>'
def tab(t): return f'<span class="tabk">{t}</span>'

def table(head, rows, cls=''):
    h = ''.join(f'<th>{x}</th>' for x in head)
    b = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<table class="t {cls}"><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table>'

def chapter(title, sub, color, *body):
    CH[0] += 1; FIG[0] = 0
    cid = f'ch{CH[0]}'
    TOC.append((CH[0], title, cid, []))
    OUT.append(f'<section class="chapter" id="{cid}" style="--cc:{color}"><header class="chead"><div class="cnum">บทที่ {CH[0]}</div><h1>{title}</h1><p>{sub}</p></header>')
    for x in body: OUT.append(x)
    OUT.append('</section>')

def sec(title, *body):
    return f'<div class="sec" id="@@SID@@"><h2><span class="sn">@@SN@@</span>{title}</h2>' + ''.join(body) + '</div>'

