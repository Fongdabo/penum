def box_solid(x0, y0, z0, x1, y1, z1):
    pts = [XYZ(x0, y0, z0), XYZ(x1, y0, z0), XYZ(x1, y1, z0), XYZ(x0, y1, z0)]
    loop = CurveLoop()
    for i in range(4):
        loop.Append(Line.CreateBound(pts[i], pts[(i + 1) % 4]))
    loops = List[CurveLoop]()
    loops.Add(loop)
    return GeometryCreationUtilities.CreateExtrusionGeometry(loops, XYZ.BasisZ, z1 - z0)

def make_box(cat, name, comment, x0, y0, z0, x1, y1, z1):
    cid = None
    for c in (cat, BuiltInCategory.OST_GenericModel):
        try:
            cc = Category.GetCategory(doc, c)
            if cc is not None and DirectShape.IsValidCategoryId(cc.Id, doc):
                cid = cc.Id
                break
        except:
            pass
    if cid is None:
        raise Exception('no valid category for ' + name)
    ds = DirectShape.CreateElement(doc, cid)
    geo = List[GeometryObject]()
    geo.Add(box_solid(min(x0, x1) * MM, min(y0, y1) * MM, z0 * MM, max(x0, x1) * MM, max(y0, y1) * MM, z1 * MM))
    ds.SetShape(geo)
    try:
        ds.Name = name
    except:
        pass
    set_text(ds, BuiltInParameter.ALL_MODEL_MARK, name)
    set_text(ds, BuiltInParameter.ALL_MODEL_INSTANCE_COMMENTS, comment)
    return ds

